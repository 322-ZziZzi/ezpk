import fs from 'node:fs';
import vm from 'node:vm';
const source=fs.readFileSync(new URL('../worker.js',import.meta.url),'utf8');
const start=source.indexOf('const BGB_LOCATION_CODES');
const end=source.indexOf('async function writeBgbAdminContentD1',start);
if(start<0||end<0)throw new Error('BGB_HELPERS_NOT_FOUND');
const ctx={Intl,Date};
ctx.cleanString=(value,max=255)=>String(value??'').trim().slice(0,max);
vm.createContext(ctx);
vm.runInContext(source.slice(start,end)+'\nglobalThis.__bgb={normalizeBgbStorageContent,normalizeBgbTeams};',ctx);
const {normalizeBgbStorageContent}=ctx.__bgb;
const loc=()=>({R1:[],R2:[],R3:[],R4:[],R5:[],R6:[],M1:[],M2:[],H1:[],H2:[],CENTER:[]});
const team=(prefix,count)=>({members:Array.from({length:count},(_,i)=>`${prefix}${i+1}`),locations:loc()});
const legacy={lastUpdated:'2026.07.17',teams:{A:team('OLD-A-',20),B:team('OLD-B-',20)}};
const partial={A:team('DRAFT-A-',7),B:team('DRAFT-B-',3)};
const draft=normalizeBgbStorageContent(legacy,partial,'draft');
const checks=[];
function check(name,ok){checks.push({name,ok:Boolean(ok)});if(!ok)throw new Error(name)}
check('draft keeps legacy public A',draft.teams.A.members[0]==='OLD-A-1'&&draft.teams.A.members.length===20);
check('draft keeps legacy public B',draft.published.teams.B.members[0]==='OLD-B-1'&&draft.published.teams.B.members.length===20);
check('draft stores partial editor A',draft.draft.teams.A.members.length===7&&draft.draft.teams.A.members[0]==='DRAFT-A-1');
check('draft keeps public lastUpdated',draft.lastUpdated==='2026.07.17'&&draft.published.lastUpdated==='2026.07.17');
const ready={A:team('NEW-A-',20),B:team('NEW-B-',20)};
const published=normalizeBgbStorageContent(draft,ready,'publish');
check('publish promotes current A',published.teams.A.members[0]==='NEW-A-1'&&published.published.teams.A.members.length===20);
check('publish promotes current B',published.teams.B.members[0]==='NEW-B-1'&&published.published.teams.B.members.length===20);
check('publish syncs draft',published.draft.teams.A.members[0]==='NEW-A-1');
check('publish stamps ISO time',/^\d{4}-\d{2}-\d{2}T/.test(published.published.publishedAt));
check('publish stamps KST date',/^\d{4}\.\d{2}\.\d{2}$/.test(published.published.lastUpdated));
const result={version:'v433',pass:true,checks,publishedAt:published.published.publishedAt,lastUpdated:published.published.lastUpdated};
fs.writeFileSync(new URL('../V433_BGB_DRAFT_PUBLISH_SMOKE.json',import.meta.url),JSON.stringify(result,null,2)+'\n');
console.log('V433 BGB draft/publish smoke PASS');
